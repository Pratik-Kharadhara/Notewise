/**
 * Real Backend API Client for Notewise
 *
 * Implements the frozen API contract from docs/api-contracts.md exactly:
 *   - POST  /api/recordings/upload          (field: "file", header: x-session-id)
 *   - GET   /api/jobs/:job_id               (poll job status)
 *   - GET   /api/jobs/:job_id/transcript    (fetch transcript)
 *   - GET   /api/jobs/:job_id/outputs/:type (fetch notes/cheatsheet/mindmap artifacts)
 *   - POST  /api/jobs/:job_id/qa            (grounded Q&A)
 *   - GET   /api/recordings                 (list recordings)
 *   - GET   /api/recordings/:id             (recording metadata / assemble from job)
 *   - PATCH /api/recordings/:id             (update recording)
 *   - DELETE /api/recordings/:id            (delete recording)
 *   - GET/POST/PATCH/DELETE /api/folders    (folder CRUD)
 */

const BASE_URL = (import.meta.env.VITE_API_BASE_URL || 'http://localhost:5000').replace(/\/$/, '');

/**
 * Returns the persistent browser session ID from localStorage.
 * Generated by SessionContext and passed via x-session-id header per project spec.
 */
function getSessionId() {
  try {
    return localStorage.getItem('notewise_session_id') || '';
  } catch {
    return '';
  }
}

async function request(path, options = {}) {
  const url = `${BASE_URL}${path}`;
  const isFormData = options.body instanceof FormData;

  const headers = isFormData
    ? { ...(options.headers || {}) }
    : { 'Content-Type': 'application/json', ...(options.headers || {}) };

  // Inject the session ID header on every request (spec §2 "Browser Session Header")
  const sessionId = getSessionId();
  if (sessionId) {
    headers['x-session-id'] = sessionId;
  }

  const response = await fetch(url, {
    ...options,
    headers,
  });

  if (!response.ok) {
    let message = `Request failed (${response.status})`;
    try {
      const payload = await response.json();
      if (payload?.message) message = payload.message;
      else if (payload?.error) message = payload.error;
    } catch {
      // Ignore JSON parse errors on non-JSON error bodies
    }
    throw new Error(message);
  }

  if (response.status === 204) return null;
  return response.json();
}

export const realApi = {
  // ─── Upload & Create Job (§2.1) ──────────────────────────────────────────
  /**
   * POST /api/recordings/upload
   * Form field: "file" (contract §2.1)
   * Response: { recording_id, job_id, status, filename }
   */
  async createRecording({ audio, title, folderId, durationSeconds, source }) {
    const formData = new FormData();
    // Contract specifies field name "file"
    formData.append('file', audio);
    if (title) formData.append('title', title);
    if (folderId) formData.append('folderId', folderId);
    if (durationSeconds != null) formData.append('durationSeconds', String(durationSeconds));
    if (source) formData.append('source', source);

    const res = await request('/api/recordings/upload', {
      method: 'POST',
      body: formData,
    });

    const jobId = res?.job_id || res?.jobId || res?.id;
    const recordingId = res?.recording_id || res?.recordingId || jobId;

    return {
      ...res,
      jobId,
      job_id: jobId,
      recordingId,
      recording_id: recordingId,
      status: res?.status || 'queued',
      filename: res?.filename,
    };
  },

  // ─── Poll Job Status (§2.2) ───────────────────────────────────────────────
  /**
   * GET /api/jobs/:job_id
   * Response: { id, recording_id, status, error_message, completed_artifacts, created_at, updated_at }
   */
  async getJobStatus(jobId) {
    const data = await request(`/api/jobs/${encodeURIComponent(jobId)}`);
    const status = data.status === 'partial' ? 'processing' : (data.status || 'queued');
    const completed = Array.isArray(data.completed_artifacts) ? data.completed_artifacts : [];

    let progress = typeof data.progress === 'number' ? data.progress : 0;
    let stage = data.stage;

    if (status === 'done') {
      progress = 100;
      stage = 'done';
    } else if (status === 'failed') {
      stage = 'failed';
    } else if (status === 'processing') {
      if (completed.includes('notes') || completed.includes('cheatsheet') || completed.includes('mindmap')) {
        stage = 'generating_notes';
        progress = Math.max(progress, 75);
      } else {
        stage = 'transcription';
        progress = Math.max(progress, 45);
      }
    } else {
      stage = 'uploaded';
      progress = Math.max(progress, 15);
    }

    return {
      ...data,
      jobId: data.id || data.job_id || data.jobId || jobId,
      job_id: data.id || data.job_id || data.jobId || jobId,
      recordingId: data.recording_id || data.recordingId || data.id,
      recording_id: data.recording_id || data.recordingId || data.id,
      status,
      stage,
      progress,
      error: data.error_message || data.error,
    };
  },

  // ─── Fetch Transcript (§2.3) ──────────────────────────────────────────────
  /**
   * GET /api/jobs/:job_id/transcript
   * Response: { id, full_text, segments: [{ start, end, text }], word_count }
   */
  async getTranscript(jobId) {
    return request(`/api/jobs/${encodeURIComponent(jobId)}/transcript`);
  },

  // ─── Fetch Generated Artifacts (§2.4) ────────────────────────────────────
  /**
   * GET /api/jobs/:job_id/outputs/:type   (type ∈ notes | cheatsheet | mindmap)
   * Response: { type, content }
   */
  async getJobOutput(jobId, type) {
    return request(`/api/jobs/${encodeURIComponent(jobId)}/outputs/${encodeURIComponent(type)}`);
  },

  // ─── Grounded Q&A (§2.5) ─────────────────────────────────────────────────
  /**
   * POST /api/jobs/:job_id/qa
   * Body: { question }
   * Response: { question, answer, grounded }
   */
  async askLectureQuestion(jobId, question) {
    return request(`/api/jobs/${encodeURIComponent(jobId)}/qa`, {
      method: 'POST',
      body: JSON.stringify({ question }),
    });
  },

  // ─── Retry Failed Outputs (§2.6) ─────────────────────────────────────────
  async retryJob(jobId) {
    return request(`/api/jobs/${encodeURIComponent(jobId)}/retry`, {
      method: 'POST',
    });
  },

  // ─── Recordings CRUD ─────────────────────────────────────────────────────
  async getRecordings() {
    return request('/api/recordings');
  },

  /**
   * Fetches recording metadata and, if artifacts are separated,
   * queries /api/jobs/:job_id/transcript and /api/jobs/:job_id/outputs/:type
   * to assemble the full recording detail for the UI.
   */
  async getRecordingById(id) {
    let rec = null;
    try {
      rec = await request(`/api/recordings/${encodeURIComponent(id)}`);
    } catch (e) {
      // Fallback: if caller passed jobId or /api/recordings/:id doesn't exist, query job endpoint
      try {
        const job = await request(`/api/jobs/${encodeURIComponent(id)}`);
        rec = {
          id: job.recording_id || job.id,
          jobId: job.id,
          title: job.filename || 'Lecture Audio',
          status: job.status === 'partial' ? 'processing' : job.status,
          createdAt: job.created_at,
          updatedAt: job.updated_at,
          durationSeconds: 1800,
          subjectLabel: 'Computer Science',
          lecturer: 'Instructor',
          transcript: [],
          notes: null,
          cheatsheet: null,
          mindmap: null,
        };
      } catch {
        throw e;
      }
    }

    const jobId = rec?.job_id || rec?.jobId || rec?.id || id;

    // Check if separate artifact endpoints need to be fetched
    const needsTranscript = !rec.transcript || rec.transcript.length === 0;
    const needsOutputs = !rec.notes || !rec.cheatsheet || !rec.mindmap;

    if (jobId && (needsTranscript || needsOutputs)) {
      const [transcriptRes, notesRes, cheatsheetRes, mindmapRes] = await Promise.allSettled([
        needsTranscript ? request(`/api/jobs/${encodeURIComponent(jobId)}/transcript`) : Promise.resolve(null),
        !rec.notes ? request(`/api/jobs/${encodeURIComponent(jobId)}/outputs/notes`) : Promise.resolve(null),
        !rec.cheatsheet ? request(`/api/jobs/${encodeURIComponent(jobId)}/outputs/cheatsheet`) : Promise.resolve(null),
        !rec.mindmap ? request(`/api/jobs/${encodeURIComponent(jobId)}/outputs/mindmap`) : Promise.resolve(null),
      ]);

      if (transcriptRes.status === 'fulfilled' && transcriptRes.value) {
        const tData = transcriptRes.value;
        const segments = Array.isArray(tData.segments)
          ? tData.segments.map((seg, i) => ({
              id: seg.id || `seg-${i}`,
              speaker: seg.speaker || 'Speaker',
              timestamp:
                seg.timestamp ||
                (typeof seg.start === 'number'
                  ? `${Math.floor(seg.start / 60)}:${String(Math.floor(seg.start % 60)).padStart(2, '0')}`
                  : '0:00'),
              text: seg.text,
            }))
          : [];
        rec.transcript = segments;
      }

      if (notesRes.status === 'fulfilled' && notesRes.value) {
        rec.notes = notesRes.value.content || notesRes.value;
      }

      if (cheatsheetRes.status === 'fulfilled' && cheatsheetRes.value) {
        rec.cheatsheet = cheatsheetRes.value.content || cheatsheetRes.value;
      }

      if (mindmapRes.status === 'fulfilled' && mindmapRes.value) {
        rec.mindmap = mindmapRes.value.content || mindmapRes.value;
      }
    }

    return rec;
  },

  async updateRecording(id, updates) {
    return request(`/api/recordings/${encodeURIComponent(id)}`, {
      method: 'PATCH',
      body: JSON.stringify(updates),
    });
  },

  async deleteRecording(id) {
    return request(`/api/recordings/${encodeURIComponent(id)}`, {
      method: 'DELETE',
    });
  },

  // ─── Folders CRUD ────────────────────────────────────────────────────────
  async getFolders() {
    return request('/api/folders');
  },

  async createFolder({ name, description, color }) {
    return request('/api/folders', {
      method: 'POST',
      body: JSON.stringify({ name, description, color }),
    });
  },

  async updateFolder(id, updates) {
    return request(`/api/folders/${encodeURIComponent(id)}`, {
      method: 'PATCH',
      body: JSON.stringify(updates),
    });
  },

  async deleteFolder(id) {
    return request(`/api/folders/${encodeURIComponent(id)}`, {
      method: 'DELETE',
    });
  },
};
